import React, { useEffect } from 'react'
import {
  CheckCircle2,
  Sparkles,
  Download,
  ExternalLink,
  Copy,
  ArrowRight,
  ShieldCheck,
  X
} from 'lucide-react'
import confetti from 'canvas-confetti'
import { GreetingConfirmation } from '../../types'
import { useWallet } from '../../context/WalletContext'

interface ConfirmationGreetingModalProps {
  data: GreetingConfirmation
  onClose: () => void
}

export const ConfirmationGreetingModal: React.FC<ConfirmationGreetingModalProps> = ({
  data,
  onClose
}) => {
  const { setCurrentView, addToast } = useWallet()

  useEffect(() => {
    if (data.isOpen) {
      // Fire celebratory confetti!
      try {
        confetti({
          particleCount: 80,
          spread: 70,
          origin: { y: 0.6 },
          colors: ['#00F29D', '#00D2FF', '#FFFFFF', '#10B981']
        })
      } catch (err) {
        // Fallback gracefully if canvas is unavailable
      }
    }
  }, [data.isOpen])

  if (!data.isOpen) return null

  const copyHash = () => {
    navigator.clipboard.writeText(data.hash)
    addToast('Copied to Clipboard', data.hash, 'info')
  }

  const handleDownloadReceipt = () => {
    const receiptText = `
========================================
   NOVAWALLET 2.4 - EXECUTION RECEIPT   
========================================
Status: CRYPTOGRAPHICALLY CONFIRMED
Action: ${data.title}
Amount: ${data.amountText} (${data.usdEquivalent})
Counterparty/Asset: ${data.recipientOrAsset}
Transaction Hash: ${data.hash}
Settlement Fee: ${data.networkFee}
Timestamp: ${data.timestamp}
Security Enclave: FIDO2 Hardware Quorum (3 of 5)
========================================
Generated by Nova Protocol Foundation
    `.trim()

    const blob = new Blob([receiptText], { type: 'text/plain' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `NovaReceipt_${data.hash.substring(0, 10)}.txt`
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
    addToast('Receipt Downloaded', 'Official execution record saved to disk.', 'success')
  }

  const handleGoToLedger = () => {
    onClose()
    setCurrentView('ledger')
    window.scrollTo({ top: 0, behavior: 'smooth' })
  }

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/85 backdrop-blur-md animate-fade-in">
      <div className="relative w-full max-w-lg rounded-3xl bg-[#0D111A] border-2 border-[#00F29D]/50 shadow-glow-lg p-6 sm:p-8 text-center overflow-hidden">
        {/* Background glow effects */}
        <div className="absolute top-0 left-1/2 -translate-x-1/2 w-64 h-32 bg-gradient-to-b from-[#00F29D]/20 to-transparent blur-2xl -z-10 pointer-events-none" />

        <button
          onClick={onClose}
          className="absolute top-5 right-5 p-1.5 text-slate-400 hover:text-white rounded-lg hover:bg-white/[0.06] transition-colors"
        >
          <X className="w-5 h-5" />
        </button>

        {/* Celebratory Checkmark Icon */}
        <div className="mx-auto w-16 h-16 rounded-2xl bg-gradient-to-tr from-[#00F29D] to-[#00D2FF] p-0.5 shadow-glow mb-4">
          <div className="w-full h-full rounded-2xl bg-[#080A0F] flex items-center justify-center">
            <CheckCircle2 className="w-9 h-9 text-[#00F29D] animate-bounce" style={{ animationDuration: '2s' }} />
          </div>
        </div>

        {/* Greeting Heading */}
        <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-[#00F29D]/15 text-[#00F29D] font-mono text-xs mb-2">
          <Sparkles className="w-3.5 h-3.5" />
          <span>Task Completed Successfully</span>
        </div>

        <h2 className="text-2xl sm:text-3xl font-extrabold text-white tracking-tight">
          {data.title}
        </h2>

        <p className="text-xs sm:text-sm text-slate-300 mt-2 leading-relaxed">
          {data.greetingText}
        </p>

        {/* Detailed Receipt Card */}
        <div className="mt-6 p-4 rounded-2xl bg-[#080A0F] border border-white/[0.08] text-left text-xs font-mono space-y-2.5">
          <div className="flex justify-between items-center pb-2 border-b border-white/[0.06]">
            <span className="text-slate-400 uppercase text-[10px]">Settled Value</span>
            <div className="text-right">
              <span className="text-sm font-bold text-white block">{data.amountText}</span>
              <span className="text-[10px] text-[#00F29D]">{data.usdEquivalent}</span>
            </div>
          </div>

          <div className="flex justify-between items-center py-1 border-b border-white/[0.04]">
            <span className="text-slate-400 uppercase text-[10px]">Counterparty / Asset</span>
            <span className="text-slate-200 font-semibold truncate max-w-[200px]">
              {data.recipientOrAsset}
            </span>
          </div>

          <div className="flex justify-between items-center py-1 border-b border-white/[0.04]">
            <span className="text-slate-400 uppercase text-[10px]">Transaction Hash</span>
            <div className="flex items-center gap-1">
              <span className="text-slate-300">
                {data.hash.substring(0, 8)}...{data.hash.substring(data.hash.length - 6)}
              </span>
              <button onClick={copyHash} className="p-1 hover:text-[#00F29D] text-slate-500">
                <Copy className="w-3 h-3" />
              </button>
            </div>
          </div>

          <div className="flex justify-between items-center py-1 border-b border-white/[0.04]">
            <span className="text-slate-400 uppercase text-[10px]">Network Gas / Commission</span>
            <span className="text-slate-300">{data.networkFee}</span>
          </div>

          <div className="flex justify-between items-center pt-1">
            <span className="text-slate-400 uppercase text-[10px]">Settled Timestamp</span>
            <span className="text-slate-400 text-[10px]">{data.timestamp}</span>
          </div>
        </div>

        {/* Action Controls */}
        <div className="mt-6 flex flex-col sm:flex-row gap-3">
          <button
            onClick={handleDownloadReceipt}
            className="flex-1 py-3 rounded-xl bg-white/[0.05] hover:bg-white/[0.1] border border-white/[0.1] text-xs font-mono text-white flex items-center justify-center gap-2 transition-colors"
          >
            <Download className="w-4 h-4 text-slate-400" />
            <span>Download Receipt</span>
          </button>

          <button
            onClick={handleGoToLedger}
            className="flex-1 py-3 rounded-xl bg-[#00F29D]/20 hover:bg-[#00F29D]/30 border border-[#00F29D]/40 text-xs font-mono text-[#00F29D] font-bold flex items-center justify-center gap-2 transition-colors"
          >
            <span>View in Ledger</span>
            <ArrowRight className="w-4 h-4" />
          </button>
        </div>

        <button
          onClick={onClose}
          className="w-full mt-3 py-3.5 rounded-xl bg-gradient-to-r from-[#00F29D] to-[#00D68A] hover:brightness-110 text-[#080A0F] font-bold text-xs tracking-wide shadow-glow transition-all"
        >
          Done &amp; Return to Dashboard
        </button>
      </div>
    </div>
  )
}

